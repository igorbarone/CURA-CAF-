"use client";
import Link from "next/link";
import { useEffect, useState } from "react";
import { formatBRL } from "../../lib/commerce/catalog";
import { api } from "../../lib/commerce/client";
import { centsToValue, track } from "../../lib/analytics";
import type { OrderView } from "../../lib/commerce/server/orders";
import { useCart } from "./cart-provider";
const LABEL: Record<string, string> = {
  pending_payment: "Aguardando pagamento",
  paid: "Pagamento confirmado",
  preparing: "Em preparação",
  expired: "Prazo de pagamento encerrado",
  payment_failed: "Pagamento não aprovado",
  cancelled: "Pedido cancelado",
  shipped: "Enviado",
  delivered: "Entregue",
  refunded: "Reembolsado",
};
const NEXT: Record<string, string> = {
  pending_payment:
    "Assim que o Asaas confirmar o pagamento, esta página é atualizada e você recebe um e-mail.",
  paid: "Pagamento confirmado. Vamos preparar o envio e você receberá o código de rastreio por e-mail.",
  preparing:
    "Seu café está sendo separado e embalado. Avisaremos quando sair para entrega.",
  expired:
    "O prazo para pagar terminou e o estoque foi liberado. Nada foi cobrado; você pode comprar de novo.",
  payment_failed:
    "Nada foi cobrado. Você pode montar o carrinho de novo e tentar outra forma de pagamento.",
  cancelled: "O pagamento foi cancelado. Nada foi cobrado.",
  shipped: "Seu pedido está a caminho.",
  delivered: "Bom café!",
  refunded: "O valor foi devolvido.",
};
export function OrderStatus() {
  const cart = useCart();
  const [order, setOrder] = useState<OrderView | null>(null);
  const [missing, setMissing] = useState(false);
  const [copied, setCopied] = useState(false);
  const [reordered, setReordered] = useState("");
  useEffect(() => {
    const params = new URLSearchParams(window.location.search);
    const id = params.get("id");
    const token = params.get("token");
    if (!id || !token) return setMissing(true);
    let timer: ReturnType<typeof setTimeout>;
    let active = true;
    const load = async () => {
      const result = await api<OrderView>(
        `/api/orders/${id}/?token=${encodeURIComponent(token)}`,
      );
      if (!active) return;
      if (!result.ok) {
        if (result.status === 404) return setMissing(true);
      } else setOrder(result.data);
      // Keep checking while the payment is pending (Pix paid on the phone).
      if (!result.ok || result.data.financialStatus === "pending_payment")
        timer = setTimeout(load, 5000);
    };
    load();
    return () => {
      active = false;
      clearTimeout(timer);
    };
  }, []);
  useEffect(() => {
    if (!order || order.financialStatus !== "paid") return;
    // "purchase" is sent once per order, and only for a server-confirmed payment.
    const key = `cura-purchase-${order.id}`;
    try {
      if (localStorage.getItem(key)) return;
      localStorage.setItem(key, "1");
    } catch {
      /* best effort */
    }
    track("purchase", {
      transaction_id: order.id,
      value: centsToValue(order.totalCents),
      shipping: centsToValue(order.shippingCents),
      items: order.items.map((item) => ({
        item_id: item.id,
        item_name: item.name,
        item_variant: item.label,
        price: centsToValue(item.unitPriceCents),
        quantity: item.quantity,
      })),
    });
  }, [order]);
  if (missing)
    return (
      <section className="empty-state">
        <h1>Pedido não encontrado.</h1>
        <p>
          Use o link completo recebido por e-mail para acompanhar seu pedido.
        </p>
      </section>
    );
  if (!order) return <p className="body-copy">Carregando o pedido…</p>;
  const pix = order.payment?.pix;
  const invoiceUrl = order.payment?.invoiceUrl;
  const pending = order.financialStatus === "pending_payment";
  const stillSold = order.items.filter((item) => cart.book[item.id]);
  return (
    <section className="order-view" aria-labelledby="order-title">
      <p className="eyebrow">PEDIDO {order.id.slice(0, 8).toUpperCase()}</p>
      <h1 id="order-title">
        {order.firstName}, obrigado.
        <br />
        <em>{LABEL[order.status] ?? order.status}.</em>
      </h1>
      <p className="order-status-text" role="status">
        {NEXT[order.status]}
      </p>
      {pix && (
        <div className="pix-box">
          <p className="eyebrow">PAGUE COM PIX</p>
          {pix.qrCodeBase64 && (
            // A data URI generated by Asaas for this charge.
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={`data:image/png;base64,${pix.qrCodeBase64}`}
              alt="QR Code Pix do pedido"
              width={220}
              height={220}
            />
          )}
          {pix.qrCode && (
            <>
              <label htmlFor="pix-code">Pix copia e cola</label>
              <textarea id="pix-code" readOnly value={pix.qrCode} rows={3} />
              <button
                type="button"
                className="button"
                onClick={async () => {
                  try {
                    await navigator.clipboard.writeText(pix.qrCode!);
                    setCopied(true);
                  } catch {
                    setCopied(false);
                  }
                }}
              >
                {copied ? "Código copiado" : "Copiar código Pix"}
              </button>
            </>
          )}
        </div>
      )}
      {pending && !order.payment && (
        <p className="availability" role="status">
          Gerando a cobrança… esta página se atualiza sozinha.
        </p>
      )}
      {invoiceUrl && (
        <div className="pix-box">
          <p className="eyebrow">PAGUE COM CARTÃO</p>
          <p>
            O cartão é digitado na página segura do Asaas. Depois do pagamento,
            você volta para este pedido.
          </p>
          <a className="button" href={invoiceUrl}>
            Pagar com cartão
          </a>
        </div>
      )}
      {pending && order.expiresAt && (
        <p className="availability">
          Pague até{" "}
          {new Date(order.expiresAt).toLocaleString("pt-BR", {
            dateStyle: "short",
            timeStyle: "short",
          })}
          . Depois disso o pedido expira e nada é cobrado.
        </p>
      )}
      {order.tracking && (
        <p className="order-tracking">
          Rastreio: <strong>{order.tracking.code}</strong>
          {order.tracking.carrier && ` · ${order.tracking.carrier}`}
        </p>
      )}
      <ul className="cart-lines order-items">
        {order.items.map((item) => (
          <li key={item.id}>
            <div>
              <h2>{item.name}</h2>
              <p>
                {item.quantity}× {item.label}
              </p>
            </div>
            <p className="cart-line-total">{formatBRL(item.lineTotalCents)}</p>
          </li>
        ))}
      </ul>
      <dl className="order-totals">
        <div>
          <dt>Subtotal</dt>
          <dd>{formatBRL(order.subtotalCents)}</dd>
        </div>
        {order.discountCents > 0 && (
          <div>
            <dt>Desconto Pix</dt>
            <dd>−{formatBRL(order.discountCents)}</dd>
          </div>
        )}
        <div>
          <dt>
            Frete · {order.shipping.company} {order.shipping.name}
            {order.shipping.volumes > 1 &&
              ` · ${order.shipping.volumes} volumes`}
          </dt>
          <dd>
            {order.shippingCents === 0
              ? "Grátis"
              : formatBRL(order.shippingCents)}
          </dd>
        </div>
        <div className="cart-total">
          <dt>Total</dt>
          <dd>{formatBRL(order.totalCents)}</dd>
        </div>
        <div>
          <dt>Entrega em</dt>
          <dd>{order.destination}</dd>
        </div>
      </dl>
      {stillSold.length > 0 && (
        <div className="order-reorder">
          <button
            type="button"
            className="button"
            onClick={() => {
              for (const item of stillSold)
                cart.add(item.id, item.quantity, { silent: true });
              setReordered("Itens adicionados ao carrinho.");
            }}
          >
            Comprar novamente
          </button>
          <p role="status">
            {reordered && (
              <>
                {reordered} <Link href="/carrinho/">Ver carrinho</Link>
              </>
            )}
          </p>
        </div>
      )}
      <p className="availability">
        Guarde este link: ele é o acesso ao seu pedido.
      </p>
    </section>
  );
}
