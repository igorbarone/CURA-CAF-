// Static export for GitHub Pages. The store's API routes (app/api, standard
// `route.ts` files) and the operations panel (app/admin, server-only pages)
// cannot be exported, so they are moved into private folders (ignored by the
// router) only while `next build` runs, and always put back, even when the
// build fails or is interrupted.
import { existsSync, renameSync, rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
const folders = [
  { live: "app/api", hidden: "app/_api-static-build" },
  { live: "app/admin", hidden: "app/_admin-static-build" },
];
for (const { live, hidden } of folders)
  if (existsSync(hidden) && !existsSync(live)) renameSync(hidden, live);
const restore = () => {
  for (const { live, hidden } of folders)
    if (existsSync(hidden)) renameSync(hidden, live);
};
for (const signal of ["SIGINT", "SIGTERM"] as const)
  process.on(signal, () => {
    restore();
    process.exit(1);
  });
// Types generated by a previous server build point at the routes hidden
// below; they are regenerated by the next server build.
rmSync(".next-server/types", { recursive: true, force: true });
let status = 1;
try {
  for (const { live, hidden } of folders)
    if (existsSync(live)) renameSync(live, hidden);
  status =
    spawnSync("npx", ["next", "build"], { stdio: "inherit" }).status ?? 1;
} finally {
  restore();
}
process.exit(status);
